function renderBlock(block: string, index: number) {
  if (block === "---") return <hr key={`line-${index}`} />;
  if (block.startsWith("# ")) return <h3 key={`heading-${index}`}>{block.slice(2)}</h3>;
  if (block.startsWith("## ")) return <h4 key={`subheading-${index}`}>{block.slice(3)}</h4>;

  const lines = block.split("\n");
  if (lines.every((line) => line.startsWith("- ") || line.startsWith("✨ "))) {
    return <ul key={`list-${index}`}>{lines.map((line) => <li key={line}>{line.replace(/^(?:- |✨ )/, "")}</li>)}</ul>;
  }

  return <p key={`paragraph-${index}`}>{lines.join(" ")}</p>;
}

export function AisuBiographyAccordion() {
  const [isOpen, setIsOpen] = useState(false);
  const accordion = useRef<HTMLElement>(null);
  const positionLockFrame = useRef<number | null>(null);

  useEffect(() => () => { if (positionLockFrame.current) cancelAnimationFrame(positionLockFrame.current); }, []);

  function toggleAccordion() {
    const root = accordion.current;
    if (!root) return;
    const initialTop = root.getBoundingClientRect().top;
    const startedAt = performance.now();
    if (positionLockFrame.current) cancelAnimationFrame(positionLockFrame.current);

    const keepStartInView = (now: number) => {
      const shift = root.getBoundingClientRect().top - initialTop;
      if (Math.abs(shift) > .5) window.scrollBy(0, shift);
      if (now - startedAt < 390) positionLockFrame.current = requestAnimationFrame(keepStartInView);
    };

    setIsOpen((open) => !open);
    positionLockFrame.current = requestAnimationFrame(keepStartInView);
  }

  return <section className={`aisu-biography${isOpen ? " is-open" : ""}`} ref={accordion}>
    <button className="aisu-biography-trigger" type="button" aria-expanded={isOpen} aria-controls="aisu-biography-content" onClick={toggleAccordion}>
      <span>Обо мне</span><span className="aisu-biography-icon" aria-hidden="true">+</span>
    </button>
    <div className="aisu-biography-divider" aria-hidden="true" />
    <div className="aisu-biography-panel" id="aisu-biography-content">
      <div className="aisu-biography-panel-inner">
        <div className="aisu-biography-content">
          <h2>Кто я на самом деле? Обо мне и моей практике.</h2>
          {biography.trim().split("\n\n").map(renderBlock)}
        </div>
      </div>
    </div>
  </section>;
}
